def seed(db):
    for name, aliases in SEEDS:
        existing = db.query(SymptomDict).filter(SymptomDict.name == name).first()
        if existing:
            # Update aliases (merge if there are new ones)
            existing_aliases = set(existing.aliases.split(",")) if existing.aliases else set()
            new_aliases = set(a.strip() for a in aliases.split(",") if a.strip())
            merged = existing_aliases | new_aliases
            existing.aliases = ",".join(sorted(merged))
        else:
            db.add(SymptomDict(name=name, aliases=aliases))
    db.commit()
    print(f"Seeded/updated {len(SEEDS)} symptoms.")


if __name__ == "__main__":
    db = SessionLocal()
    seed(db)
    db.close()
